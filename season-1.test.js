const test=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {decode,role,formatRoute,init}=require('./season-1.js');
test('bad storage, unknown roles and empty plans are safe',()=>{
  assert.deepEqual(decode('{'),{});
  assert.deepEqual(decode('[]'),{});
  assert.equal(role('constructor').card,'');
  assert.equal(role('combat').card,'war-leader');
  assert.equal(role('growth').card,'engineer');
  assert.match(formatRoute({}),/Fallback route\nTarget city: Not set/);
  assert.match(formatRoute({'primary-city':'City X:22 Y:44'}),/Primary route\nTarget city: City X:22 Y:44/);
});
test('checklist, class selection and route restore through entry-point handlers',async()=>{
  const html=readFileSync(__dirname+'/season-1.html','utf8');
  const single=(extras={})=>({listeners:{},addEventListener(k,v){this.listeners[k]=v},focus(){},select(){},classList:{toggle(_key,on){this.on=on}},...extras});
  const ids=Object.fromEntries([...html.matchAll(/\bid="([^"]+)"/g)].map(([,id])=>[id,single()]));
  const boxes=[...html.matchAll(/data-check="([^"]+)"/g)].map(([,key])=>single({dataset:{check:key}}));
  const fields=[...html.matchAll(/id="((?:primary|fallback)-[^"]+)"[^>]*data-route/g)].map(([,key])=>Object.assign(ids[key],{id:key}));
  assert.equal(boxes.length,8);assert.equal(fields.length,10);
  const doc={getElementById:id=>ids[id],querySelectorAll:q=>q==='[data-check]'?boxes:fields};
  let persisted,copied;
  const win={localStorage:{getItem:()=>persisted,setItem:(_,value)=>{persisted=value}},navigator:{clipboard:{async writeText(v){copied=v}}}};
  init(doc,win);
  boxes[0].checked=true;boxes[0].listeners.change();
  assert.equal(ids['progress-text'].textContent,'1 of 8 complete');
  ids['class-role'].value='combat';ids['class-role'].listeners.change();
  assert.equal(ids['war-leader'].classList.on,true);
  ids['primary-city'].value='Alpha X:22 Y:44';ids['primary-city'].listeners.input();
  await ids['copy-plan'].listeners.click();
  assert.match(copied,/Alpha X:22 Y:44/);
  boxes[0].checked=false;ids['primary-city'].value='';ids['class-role'].value='';
  init(doc,win);
  assert.equal(boxes[0].checked,true);assert.equal(ids['primary-city'].value,'Alpha X:22 Y:44');assert.equal(ids['class-role'].value,'combat');
  win.navigator={};
  await ids['copy-plan'].listeners.click();
  assert.equal(ids['plan-text'].hidden,false);assert.match(ids['plan-text'].value,/Alpha X:22 Y:44/);
  assert.match(html,/src="\.\/site-nav\.js"/);
});
